// lib.rs
//
// Proof-of-Work (PoW) Consensus Engine for rusty-jio
//
// Integrates:
// 1. PowHash (cSHAKE256 header pre-hash)
// 2. Xoshiro256++ (PRNG matrix generator)
// 3. 64x64 GEMV (Matrix-Vector multiplication)
// 4. PowB3Hash (BLAKE3 Keyed finalizer)
// 5. Uint256 difficulty comparison

pub mod matrix;
pub mod xoshiro;

use jio_hashes::{Hash, Hasher, HasherBase, PowB3Hash, PowHash};
use jio_math::Uint256;
use matrix::{Matrix, hash_to_vector, vector_to_hash};
use thiserror::Error;
use xoshiro::Xoshiro256PlusPlus;

#[derive(Error, Debug, PartialEq, Eq)]
pub enum PowError {
    #[error("Proof of work hash {0} exceeds target {1}")]
    DifficultyNotMet(Uint256, Uint256),
}

/// Evaluates the complete 2-stage Proof-of-Work algorithm for a block candidate.
///
/// Steps:
/// 1. `pow_hash` = PowHash::finalize_with_nonce(nonce)
/// 2. `matrix` = generated by Xoshiro256++ seeded from `pre_pow_hash`
/// 3. `vector` = 64 nibbles extracted from `pow_hash`
/// 4. `product` = matrix.mul_vector(vector)
/// 5. `matrix_hash` = vector_to_hash(product)
/// 6. `final_pow` = PowB3Hash(pow_hash || matrix_hash)
/// 7. Convert `final_pow` into `Uint256`
#[inline]
pub fn calculate_pow(pre_pow_hash: Hash, timestamp: u64, nonce: u64) -> (Hash, Uint256) {
    // Stage 1: Header pre-hash with nonce injection
    let hasher = PowHash::from_pre_pow_and_timestamp(pre_pow_hash, timestamp);
    let pow_hash = hasher.finalize_with_nonce(nonce);

    // Stage 2: Memory-hard 64x64 GEMV
    let mut rng = Xoshiro256PlusPlus::new(pre_pow_hash.to_le_u64());
    let matrix = Matrix::generate(&mut rng);
    let vector = hash_to_vector(&pow_hash);
    let product = matrix.mul_vector(&vector);
    let matrix_hash = vector_to_hash(&product);

    // Stage 3: BLAKE3 Keyed Finalization
    let mut b3 = PowB3Hash::new();
    b3.update(pow_hash.as_bytes());
    b3.update(matrix_hash.as_bytes());
    let final_hash = Hasher::finalize(b3);

    let pow_val = Uint256::from_le_bytes(final_hash.as_bytes());
    (final_hash, pow_val)
}

/// Verifies whether a candidate block header fulfills the target difficulty requirement.
#[inline]
pub fn check_proof_of_work(
    pre_pow_hash: Hash,
    timestamp: u64,
    nonce: u64,
    target: Uint256,
) -> Result<Hash, PowError> {
    let (final_hash, pow_val) = calculate_pow(pre_pow_hash, timestamp, nonce);
    if pow_val <= target {
        Ok(final_hash)
    } else {
        Err(PowError::DifficultyNotMet(pow_val, target))
    }
}

/// Computes the block level based on leading zeros of the PoW value.
///
/// Block level is used in Kaspa / BlockDAG networks to organize blocks
/// into hierarchical sub-DAGs for fast reachability indexing.
#[inline]
pub fn calc_block_level(pow_value: Uint256, max_block_level: u8) -> u8 {
    if pow_value == Uint256::ZERO {
        return max_block_level;
    }
    let leading_zeros = pow_value.leading_zeros() as u8;
    leading_zeros.min(max_block_level)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_pow_calculation_determinism() {
        let pre_pow = Hash::from_le_u64([1, 2, 3, 4]);
        let timestamp = 1700000000;
        let nonce = 42;

        let (h1, v1) = calculate_pow(pre_pow, timestamp, nonce);
        let (h2, v2) = calculate_pow(pre_pow, timestamp, nonce);

        assert_eq!(h1, h2);
        assert_eq!(v1, v2);

        // Different nonce -> completely different hash
        let (h3, _) = calculate_pow(pre_pow, timestamp, nonce + 1);
        assert_ne!(h1, h3);
    }

    #[test]
    fn test_check_proof_of_work_validation() {
        let pre_pow = Hash::from_le_u64([100, 200, 300, 400]);
        let timestamp = 1700000000;
        let nonce = 999;

        let (_, pow_val) = calculate_pow(pre_pow, timestamp, nonce);

        // Target greater than or equal to pow_val -> OK
        assert!(check_proof_of_work(pre_pow, timestamp, nonce, pow_val).is_ok());
        assert!(check_proof_of_work(pre_pow, timestamp, nonce, Uint256::MAX).is_ok());

        // Target less than pow_val -> Error
        if pow_val > Uint256::ZERO {
            let impossible_target = pow_val - Uint256::from_u64(1);
            assert!(matches!(
                check_proof_of_work(pre_pow, timestamp, nonce, impossible_target),
                Err(PowError::DifficultyNotMet(_, _))
            ));
        }
    }

    #[test]
    fn test_block_level() {
        let max_level = 32;
        assert_eq!(calc_block_level(Uint256::ZERO, max_level), max_level);
        assert_eq!(calc_block_level(Uint256::MAX, max_level), 0);
    }
}
